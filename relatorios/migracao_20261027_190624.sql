DECLARE col text;
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN
    FOREACH col IN ARRAY TG_ARGV LOOP
      IF to_jsonb(NEW) -> col IS NOT DISTINCT FROM to_jsonb(OLD) -> col THEN
        NEW := jsonb_populate_record(NEW, jsonb_build_object(col, statement_timestamp()));
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
END $$
;

